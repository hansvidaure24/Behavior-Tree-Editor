// @ts-check
/** @import { TreeState } from './types.js' */
/** Export functions — engine adapters, Mermaid, ASCII tree, Markdown docs. */
export const Exports = (() => {
  /**
   * @param {Blob} blob
   * @param {string} filename
   */
  function download(blob, filename) {
    const a = document.createElement("a");
    a.href = URL.createObjectURL(blob);
    a.download = filename;
    a.click();
    URL.revokeObjectURL(a.href);
  }

  /**
   * C# MonoBehaviour that registers a stub for every action and condition with the tree's BehaviorTreeRunner.
   * Leaves bind by name (case, spaces and punctuation ignored), so one stub covers every node of that name.
   * Conditions/guards that use key/op/value parameters are checked against the blackboard and need no code.
   * @param {TreeState} state
   * @param {string} title
   * @param {string} className
   * @param {string} name File slug of the .bt.json
   * @returns {{code: string, actions: number, conditions: number}}
   */
  function unityBindings(state, title, className, name) {
    const key = n => n.toLowerCase().replace(/[^a-z0-9]/g, "");
    const method = n => {
      const m = n.split(/[^a-zA-Z0-9]+/).filter(Boolean).map(w => w[0].toUpperCase() + w.slice(1)).join("") || "Node";
      return /^[0-9]/.test(m) ? "_" + m : m;
    };
    /** @param {(n: import('./types.js').BTNode) => boolean} pick */
    const collect = pick => {
      const byKey = new Map();
      for (const n of state.nodes) {
        if (!pick(n)) continue;
        const k = key(n.name);
        if (!byKey.has(k)) byKey.set(k, { name: n.name, params: new Map(), count: 0 });
        const e = byKey.get(k);
        e.count++;
        for (const [p, v] of Object.entries(n.parameters || {})) if (!e.params.has(p)) e.params.set(p, v);
      }
      return [...byKey.values()].sort((a, b) => a.name.localeCompare(b.name));
    };
    const usesBlackboard = n => n.parameters && n.parameters.key !== undefined;
    const actions = collect(n => n.type === "action");
    const conditions = collect(n => (n.type === "condition" || n.type === "guard") && !usesBlackboard(n));
    const blackboardChecks = state.nodes.filter(n => (n.type === "condition" || n.type === "guard") && usesBlackboard(n)).length;
    /** @param {string} p @param {any} v */
    const getter = (p, v) => {
      const local = method(p).replace(/^./, c => c.toLowerCase());
      if (typeof v === "string") return `string ${local} = ctx.Params.GetString("${p}");`;
      if (typeof v === "boolean") return `bool ${local} = ctx.Params.GetBool("${p}");`;
      return `float ${local} = ctx.Params.GetFloat("${p}");`;
    };
    const paramHint = e => e.params.size ? "\n        // " + [...e.params].map(([p, v]) => getter(p, v)).join("\n        // ") : "";
    const used = e => e.count > 1 ? ` (${e.count} nodes)` : "";

    const code = `// Auto-generated by Behavior Tree Editor — ${title}
// Game code for "${name}.bt.json". Put this on the GameObject with the BehaviorTreeRunner that plays that file,
// then replace the TODOs. Runtime: adapters/unity (namespace BehaviorTreeRuntime).
${blackboardChecks ? `// ${blackboardChecks} condition/guard node(s) compare blackboard keys and need no code here.\n` : ""}using BehaviorTreeRuntime;
using UnityEngine;

[RequireComponent(typeof(BehaviorTreeRunner))]
public class ${className}Bindings : MonoBehaviour
{
    void Awake()
    {
        var bindings = GetComponent<BehaviorTreeRunner>().Bindings;
${[...actions.map(a => `        bindings.RegisterAction(${JSON.stringify(a.name)}, ${method(a.name)}, onAbort: Stop${method(a.name)});`),
  ...conditions.map(c => `        bindings.RegisterCondition(${JSON.stringify(c.name)}, ${method(c.name)});`)].join("\n")}
    }
${actions.map(a => `
    // Action "${a.name}"${used(a)}. Return Running while it is in progress, then Success or Failure.
    NodeStatus ${method(a.name)}(BTContext ctx)
    {${paramHint(a)}
        // TODO: implement
        return NodeStatus.Success;
    }

    // Called if a higher-priority branch cuts "${a.name}" off while it is Running.
    void Stop${method(a.name)}(BTContext ctx)
    {
    }`).join("\n")}
${conditions.map(c => `
    // Condition "${c.name}"${used(c)}.
    bool ${method(c.name)}(BTContext ctx)
    {${paramHint(c)}
        // TODO: implement
        return false;
    }`).join("\n")}
}
`;
    return { code, actions: actions.length, conditions: conditions.length };
  }

  /**
   * Download starter game bindings for an engine: a C# MonoBehaviour for the Unity runtime, C++/GDScript stubs for the others.
   * @param {TreeState} state
   * @param {"unity" | "unreal" | "godot"} engine
   * @param {(msg: string) => void} toast
   */
  function engineAdapter(state, engine, toast) {
    if (state.nodes.length === 0) { toast("Nothing to export"); return; }
    const actions = [...new Set(state.nodes.filter(n => n.type === "action").map(n => n.name))].sort();
    const conditions = [...new Set(state.nodes.filter(n => n.type === "condition").map(n => n.name))].sort();
    const title = state.title || "Untitled";
    const className = title.replace(/[^a-zA-Z0-9]/g, "").replace(/^[0-9]+/, "") || "BehaviorTree";
    const name = title.toLowerCase().replace(/\s+/g, "-").replace(/[^a-z0-9_-]/g, "") || "tree";

    let code;
    if (engine === "unity") {
      const unity = unityBindings(state, title, className, name);
      download(new Blob([unity.code], { type: "text/plain" }), className + "Bindings.cs");
      toast(`Exported C# bindings — ${unity.actions} actions, ${unity.conditions} conditions`);
      return;
    } else if (engine === "unreal") {
      const header = `// Auto-generated by BehaviorTreeEditor — ${title}
// Load "${name}.bt.json" at runtime with your BT runner
#pragma once
#include "CoreMinimal.h"
#include "${className}Actions.generated.h"

UENUM(BlueprintType)
enum class EBTStatus : uint8 { Success, Failure, Running };

UCLASS(Blueprintable)
class U${className}Actions : public UObject
{
    GENERATED_BODY()
public:
${actions.map(a => `    UFUNCTION(BlueprintCallable)
    EBTStatus ${a.replace(/[^a-zA-Z0-9_]/g, "")}();`).join("\n")}
${conditions.map(c => `    UFUNCTION(BlueprintCallable)
    bool ${c.replace(/[^a-zA-Z0-9_]/g, "")}();`).join("\n")}
};
`;
      const cpp = `// Auto-generated by BehaviorTreeEditor — ${title}
#include "${className}Actions.h"
${actions.map(a => {
  const fn = a.replace(/[^a-zA-Z0-9_]/g, "");
  return `\nEBTStatus U${className}Actions::${fn}()\n{\n    // TODO: implement ${a}\n    return EBTStatus::Success;\n}`;
}).join("\n")}
${conditions.map(c => {
  const fn = c.replace(/[^a-zA-Z0-9_]/g, "");
  return `\nbool U${className}Actions::${fn}()\n{\n    // TODO: implement ${c}\n    return true;\n}`;
}).join("\n")}
`;
      download(new Blob([header], { type: "text/plain" }), className + "Actions.h");
      download(new Blob([cpp], { type: "text/plain" }), className + "Actions.cpp");
      toast(`Exported Unreal C++ adapter — ${actions.length} actions, ${conditions.length} conditions (header + source)`);
      return;
    } else {
      code = `# Auto-generated by BehaviorTreeEditor — ${title}
# Load "${name}.bt.json" at runtime with BehaviorTreeRunner
extends Node
class_name ${className}Actions
${actions.map(a => `
func ${a.replace(/[^a-zA-Z0-9_]/g, "_").toLowerCase()}() -> int:
\t# TODO: implement ${a}
\t# Return: 0 = Success, 1 = Failure, 2 = Running
\treturn 0`).join("\n")}
${conditions.map(c => `
func ${c.replace(/[^a-zA-Z0-9_]/g, "_").toLowerCase()}() -> bool:
\t# TODO: implement ${c}
\treturn true`).join("\n")}
`;
    }
    download(new Blob([code], { type: "text/plain" }), className + "Actions.gd");
    toast(`Exported GDScript adapter — ${actions.length} actions, ${conditions.length} conditions`);
  }

  /**
   * Copy the tree as a Mermaid flowchart.
   * @param {TreeState} state
   * @param {(msg: string) => void} toast
   */
  function mermaid(state, toast) {
    if (state.nodes.length === 0) { toast("Nothing to export"); return; }
    const nodeById = {};
    for (const n of state.nodes) nodeById[n.id] = n;
    const safe = id => id.replace(/[^a-zA-Z0-9_]/g, "_");
    const label = n => `${n.type}${n.name ? ": " + n.name.replace(/"/g, "#quot;") : ""}`;
    const lines = ["graph TD"];
    const visited = new Set();
    function walk(id) {
      const n = nodeById[id];
      if (!n || visited.has(id)) return;
      visited.add(id);
      const sid = safe(id);
      if (n.category === "composite") lines.push(`  ${sid}["${label(n)}"]`);
      else if (n.category === "decorator") lines.push(`  ${sid}{{"${label(n)}"}}`);
      else lines.push(`  ${sid}(["${label(n)}"])`);
      for (const cid of n.children) { lines.push(`  ${sid} --> ${safe(cid)}`); walk(cid); }
    }
    if (state.root) walk(state.root);
    else for (const n of state.nodes) if (!state.nodes.some(p => p.children.includes(n.id))) walk(n.id);
    navigator.clipboard.writeText(lines.join("\n")).then(() => toast("Mermaid diagram copied to clipboard"));
  }

  /**
   * Copy the tree as an indented ASCII outline.
   * @param {TreeState} state
   * @param {(msg: string) => void} toast
   */
  function ascii(state, toast) {
    if (state.nodes.length === 0) { toast("Nothing to export"); return; }
    const nodeById = {};
    for (const n of state.nodes) nodeById[n.id] = n;
    const label = n => `[${n.type}]${n.name ? " " + n.name : ""}`;
    const lines = [];
    const visited = new Set();
    function walk(id, prefix, isLast) {
      const n = nodeById[id];
      if (!n || visited.has(id)) return;
      visited.add(id);
      const connector = prefix === "" ? "" : (isLast ? "└── " : "├── ");
      lines.push(prefix + connector + label(n));
      const childPrefix = prefix === "" ? "" : prefix + (isLast ? "    " : "│   ");
      for (let i = 0; i < n.children.length; i++) walk(n.children[i], childPrefix, i === n.children.length - 1);
    }
    if (state.root) walk(state.root, "", true);
    else for (const n of state.nodes) if (!state.nodes.some(p => p.children.includes(n.id))) walk(n.id, "", true);
    navigator.clipboard.writeText(lines.join("\n")).then(() => toast("ASCII tree copied to clipboard"));
  }

  const mdEsc = s => s.replace(/\|/g, "\\|");

  /**
   * Download Markdown documentation for the tree.
   * @param {TreeState} state
   * @param {(msg: string) => void} toast
   */
  function markdown(state, toast) {
    if (state.nodes.length === 0) { toast("Nothing to export"); return; }
    const nodeById = {};
    for (const n of state.nodes) nodeById[n.id] = n;
    const lines = [];
    lines.push(`# ${state.title || "Behavior Tree"}`);
    if (state.description) lines.push("", state.description);

    const cats = { composite: 0, decorator: 0, leaf: 0 };
    for (const n of state.nodes) cats[n.category] = (cats[n.category] || 0) + 1;
    lines.push("", "## Overview", "");
    lines.push(`- **Nodes:** ${state.nodes.length} (${cats.composite} composites, ${cats.decorator} decorators, ${cats.leaf} leaves)`);
    let maxD = 0;
    const dv = new Set();
    function calcD(id, d) { if (dv.has(id)) return; dv.add(id); if (d > maxD) maxD = d; const n = nodeById[id]; if (n) for (const c of n.children) calcD(c, d + 1); }
    if (state.root) calcD(state.root, 0);
    lines.push(`- **Max depth:** ${maxD}`);

    lines.push("", "## Tree Structure", "");
    lines.push("```");
    const aw = new Set();
    function asciiWalk(id, prefix, isLast) {
      const n = nodeById[id];
      if (!n || aw.has(id)) return;
      aw.add(id);
      const connector = prefix === "" ? "" : (isLast ? "└── " : "├── ");
      const pStr = Object.entries(n.parameters).map(([k, v]) => `${k}=${v}`).join(", ");
      lines.push(prefix + connector + `[${n.type}] ${n.name}` + (pStr ? ` (${pStr})` : ""));
      const cp = prefix === "" ? "" : prefix + (isLast ? "    " : "│   ");
      for (let i = 0; i < n.children.length; i++) asciiWalk(n.children[i], cp, i === n.children.length - 1);
    }
    if (state.root) asciiWalk(state.root, "", true);
    lines.push("```");

    const actions = state.nodes.filter(n => n.type === "action");
    const conditions = state.nodes.filter(n => n.type === "condition");
    if (actions.length > 0) {
      lines.push("", "## Actions", "");
      lines.push("| Name | Description | Parameters |");
      lines.push("|------|-------------|------------|");
      for (const a of actions) {
        const params = Object.entries(a.parameters).map(([k, v]) => `\`${k}=${v}\``).join(", ") || "—";
        lines.push(`| **${mdEsc(a.name)}** | ${mdEsc(a.description || "—")} | ${params} |`);
      }
    }
    if (conditions.length > 0) {
      lines.push("", "## Conditions", "");
      lines.push("| Name | Description | Parameters |");
      lines.push("|------|-------------|------------|");
      for (const c of conditions) {
        const params = Object.entries(c.parameters).map(([k, v]) => `\`${k}=${v}\``).join(", ") || "—";
        lines.push(`| **${mdEsc(c.name)}** | ${mdEsc(c.description || "—")} | ${params} |`);
      }
    }

    lines.push("", "---", `*Generated by Behavior Tree Editor — ${new Date().toLocaleDateString()}*`);
    const md = lines.join("\n");
    const name = (state.title || "tree").toLowerCase().replace(/\s+/g, "-").replace(/[^a-z0-9_-]/g, "");
    download(new Blob([md], { type: "text/markdown" }), name + ".md");
    toast("Markdown documentation exported");
  }

  return { download, engineAdapter, mermaid, ascii, markdown };
})();
